export function getIcon(name?: string): LucideIcon {
  if (!name) return Wrench;
  return ICONS[name] ?? Wrench;
}

interface IconProps {
  name?: string;
  className?: string;
  strokeWidth?: number;
}

export function Icon({ name, className, strokeWidth = 2 }: IconProps) {
  const Resolved = getIcon(name);
  return createElement(Resolved, {
    className,
    strokeWidth,
    'aria-hidden': true,
  });
}
